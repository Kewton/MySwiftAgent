"""Unit tests for Issue #410: user_input_schema end-to-end propagation.

This module tests that user_input_schema generated by LLM is properly
propagated through the entire system:
- JobGenerationResult (orchestrator.py)
- JobGeneratorResponse (job_generator.py)
- Adapter conversion (_convert_result)

Test Plan:
1. JobGenerationResult has user_input_schema field
2. JobGeneratorResponse has user_input_schema field
3. _convert_result propagates user_input_schema
4. _build_result sets user_input_schema from analysis
"""

from typing import Any

from aiagent.langgraph.jobGeneratorV2.nodes.job_analyzer import (
    AnalyzedTask,
    InterfaceDefinition,
    JobAnalysisResponse,
)
from aiagent.langgraph.jobGeneratorV2.orchestrator import (
    JobGenerationResult,
)
from app.schemas.job_generator import JobGeneratorResponse


class TestJobGenerationResultUserInputSchema:
    """Tests for user_input_schema field in JobGenerationResult."""

    def test_job_generation_result_has_user_input_schema_field(self) -> None:
        """JobGenerationResult should have user_input_schema field.

        AC-1: JobGenerationResult data class includes user_input_schema
        """
        result = JobGenerationResult(success=True)
        assert hasattr(result, "user_input_schema"), (
            "JobGenerationResult should have user_input_schema field"
        )

    def test_user_input_schema_default_is_none(self) -> None:
        """user_input_schema should default to None.

        AC-1: Default value is None for backward compatibility
        """
        result = JobGenerationResult(success=True)
        assert result.user_input_schema is None, (
            "user_input_schema should default to None"
        )

    def test_user_input_schema_can_be_set(self) -> None:
        """user_input_schema can be set with schema values.

        AC-1: user_input_schema field accepts dict values
        """
        schema = {
            "type": "object",
            "properties": {
                "keyword": {"type": "string"},
                "email": {"type": "string", "format": "email"},
            },
            "required": ["keyword", "email"],
        }
        result = JobGenerationResult(success=True, user_input_schema=schema)
        assert result.user_input_schema == schema
        assert "keyword" in result.user_input_schema["properties"]
        assert "email" in result.user_input_schema["properties"]


