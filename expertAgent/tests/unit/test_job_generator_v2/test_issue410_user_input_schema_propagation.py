class TestBuildResultUserInputSchema:
    """Tests for user_input_schema in _build_result method."""

    def test_build_result_sets_user_input_schema_from_analysis(self) -> None:
        """_build_result should set user_input_schema from JobAnalysisResponse.

        AC-1: user_input_schema from analysis is propagated to result
        """

        from aiagent.langgraph.jobGeneratorV2.orchestrator import (
            JobGenerationOrchestrator,
        )
        from aiagent.langgraph.jobGeneratorV2.types import (
            ParallelExecutionResult,
            TaskResult,
            UnifiedTaskIdentifier,
        )

        orchestrator = JobGenerationOrchestrator()

        user_input_schema: dict[str, Any] = {
            "type": "object",
            "properties": {
                "keyword": {"type": "string"},
                "email": {"type": "string"},
            },
        }

        analysis = JobAnalysisResponse(
            tasks=[
                AnalyzedTask(
                    task_id="task_001",
                    name="Test",
                    description="Test",
                    task_type="test",
                    recommended_api="/api/test",
                )
            ],
            interfaces={
                "task_001": InterfaceDefinition(
                    input_schema={"type": "object"},
                    output_schema={"type": "object"},
                )
            },
            user_input_schema=user_input_schema,
        )

        registration = {"job_master_id": "master-123"}

        identifiers = [
            UnifiedTaskIdentifier(task_id="task_001", task_master_id="tm-001")
        ]

        workflow_result = ParallelExecutionResult(
            successful_tasks=[
                TaskResult(
                    task_id="task_001",
                    success=True,
                    workflow={"workflow_name": "test"},
                )
            ],
            failed_tasks=[],
            total_execution_time_ms=100.0,
        )

        result = orchestrator._build_result(
            analysis, registration, identifiers, workflow_result
        )

        assert result.success is True
        assert result.user_input_schema is not None, (
            "_build_result should set user_input_schema from analysis"
        )
        assert result.user_input_schema == user_input_schema

    def test_build_result_user_input_schema_empty_when_analysis_has_none(
        self,
    ) -> None:
        """_build_result should handle empty user_input_schema from analysis.

        AC-1: Backward compatibility when analysis has empty schema
        """
        from aiagent.langgraph.jobGeneratorV2.orchestrator import (
            JobGenerationOrchestrator,
        )
        from aiagent.langgraph.jobGeneratorV2.types import (
            ParallelExecutionResult,
            TaskResult,
            UnifiedTaskIdentifier,
        )

        orchestrator = JobGenerationOrchestrator()

        analysis = JobAnalysisResponse(
            tasks=[
                AnalyzedTask(
                    task_id="task_001",
                    name="Test",
                    description="Test",
                    task_type="test",
                    recommended_api="/api/test",
                )
            ],
            interfaces={},
            user_input_schema={},  # Empty schema
        )

        registration = {"job_master_id": "master-123"}
        identifiers = [
            UnifiedTaskIdentifier(task_id="task_001", task_master_id="tm-001")
        ]
        workflow_result = ParallelExecutionResult(
            successful_tasks=[
                TaskResult(
                    task_id="task_001",
                    success=True,
                    workflow={"workflow_name": "test"},
                )
            ],
            failed_tasks=[],
            total_execution_time_ms=100.0,
        )

        result = orchestrator._build_result(
            analysis, registration, identifiers, workflow_result
        )

        # Empty dict is converted to None or remains empty
        assert result.user_input_schema is None or result.user_input_schema == {}
